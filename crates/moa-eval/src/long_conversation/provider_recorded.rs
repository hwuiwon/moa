//! Recorded scripted LLM provider for deterministic transcript replay.

use std::sync::{Arc, Mutex};

use async_trait::async_trait;
use moa_core::transcript::{ProviderEvent, Transcript};
use moa_core::{
    error::MoaError, error::Result as MoaResult, traits::LLMProvider,
    types::completion::CompletionContent, types::completion::CompletionRequestView,
    types::completion::CompletionResponse, types::completion::CompletionStream,
    types::completion::SharedCompletionRequest, types::completion::StopReason,
    types::completion::TokenUsage, types::context::MessageRole, types::identifiers::ModelId,
    types::model::ModelCapabilities, types::model::TokenPricing, types::model::ToolCallFormat,
};

const COMPACTION_MAX_OUTPUT_TOKENS: usize = 700;
const RECORDED_COMPACTION_SUMMARY: &str =
    "Recorded checkpoint summary for deterministic long-conversation replay.";

/// Errors returned by [`RecordedScriptedProvider`].
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum RecordedProviderError {
    /// Replay was asked for more provider turns than the transcript contains.
    #[error(
        "recorded transcript exhausted at turn {turn_index}; transcript contains {total_turns} turns"
    )]
    TranscriptExhausted {
        /// Zero-based requested turn index.
        turn_index: usize,
        /// Total recorded turns.
        total_turns: usize,
    },
    /// The compiled request diverged from the scripted user turn.
    #[error(
        "recorded transcript mismatch at turn {turn_index}: expected user message {expected:?}, got {actual:?}"
    )]
    TranscriptMismatch {
        /// Expected user text from the transcript.
        expected: String,
        /// Actual latest user text in the provider request.
        actual: String,
        /// Zero-based turn index.
        turn_index: usize,
    },
    /// Internal replay state could not be accessed.
    #[error("recorded provider state lock poisoned: {0}")]
    StateLockPoisoned(String),
}

/// LLM provider that replays a JSONL transcript in order.
#[derive(Debug, Clone)]
pub struct RecordedScriptedProvider {
    transcript: Arc<Transcript>,
    cursor: Arc<Mutex<usize>>,
    strict_matching: bool,
}

impl RecordedScriptedProvider {
    /// Creates a strict provider that checks the latest user message for every turn.
    #[must_use]
    pub fn new(transcript: Transcript) -> Self {
        Self::with_strict_matching(transcript)
    }

    /// Creates a provider that requires request user text to match the transcript.
    #[must_use]
    pub fn with_strict_matching(transcript: Transcript) -> Self {
        Self {
            transcript: Arc::new(transcript),
            cursor: Arc::new(Mutex::new(0)),
            strict_matching: true,
        }
    }

    /// Returns whether request/user strict matching is enabled.
    #[must_use]
    pub const fn strict_matching(&self) -> bool {
        self.strict_matching
    }

    /// Returns the current zero-based replay cursor.
    pub fn cursor(&self) -> Result<usize, RecordedProviderError> {
        self.cursor
            .lock()
            .map(|cursor| *cursor)
            .map_err(|error| RecordedProviderError::StateLockPoisoned(error.to_string()))
    }

    /// Advances replay and returns the next recorded provider events exactly as stored.
    ///
    /// Internal checkpoint summarization requests are answered deterministically and do not advance
    /// the transcript cursor because they are generated by the harness, not by a scripted user turn.
    pub fn complete_events<R: CompletionRequestView + ?Sized>(
        &self,
        request: &R,
    ) -> Result<Vec<ProviderEvent>, RecordedProviderError> {
        if is_compaction_request(request) {
            return Ok(recorded_compaction_events());
        }

        let mut cursor = self
            .cursor
            .lock()
            .map_err(|error| RecordedProviderError::StateLockPoisoned(error.to_string()))?;
        let turn_index = *cursor;
        let turn = self.transcript.turns.get(turn_index).ok_or(
            RecordedProviderError::TranscriptExhausted {
                turn_index,
                total_turns: self.transcript.turns.len(),
            },
        )?;

        if self.strict_matching {
            let actual = latest_user_message(request).unwrap_or_default();
            if actual != turn.user.text {
                return Err(RecordedProviderError::TranscriptMismatch {
                    expected: turn.user.text.clone(),
                    actual,
                    turn_index,
                });
            }
        }

        *cursor += 1;
        Ok(turn.expected.clone())
    }

    /// Advances replay and returns a buffered MOA completion stream.
    pub fn complete_recorded<R: CompletionRequestView + ?Sized>(
        &self,
        request: &R,
    ) -> Result<CompletionStream, RecordedProviderError> {
        let events = self.complete_events(request)?;
        Ok(CompletionStream::from_response(response_from_events(
            events,
            self.capabilities().model_id,
        )))
    }
}

impl Default for RecordedScriptedProvider {
    fn default() -> Self {
        Self::with_strict_matching(Transcript {
            version: 1,
            scenario: "empty".to_string(),
            turns: Vec::new(),
        })
    }
}

#[async_trait]
impl LLMProvider for RecordedScriptedProvider {
    fn name(&self) -> &str {
        "recorded"
    }

    fn capabilities(&self) -> ModelCapabilities {
        ModelCapabilities {
            model_id: ModelId::new("recorded-scripted"),
            context_window: 128_000,
            max_output: 16_384,
            supports_tools: true,
            supports_vision: false,
            supports_prefix_caching: true,
            cache_ttl: None,
            tool_call_format: ToolCallFormat::Anthropic,
            pricing: TokenPricing {
                input_per_mtok: 0.0,
                output_per_mtok: 0.0,
                cached_input_per_mtok: Some(0.0),
                cache_write_5m_per_mtok: None,
                cache_write_1h_per_mtok: None,
            },
            native_tools: Vec::new(),
        }
    }

    async fn complete(&self, request: SharedCompletionRequest) -> MoaResult<CompletionStream> {
        self.complete_recorded(&request)
            .map_err(|error| MoaError::ProviderError(error.to_string()))
    }
}

fn latest_user_message<R: CompletionRequestView + ?Sized>(request: &R) -> Option<String> {
    request
        .messages()
        .iter()
        .rev()
        .find(|message| message.role == MessageRole::User && !is_synthetic_user_section(message))
        .map(|message| message.content.clone())
}

/// Pipeline-injected user-role sections that are not the human turn.
///
/// The context pipeline inserts these near the active user turn (after
/// replayed history) so they cannot disturb prompt-cache reuse of the frozen
/// history region; transcript matching must skip them when locating the real
/// user message.
fn is_synthetic_user_section(message: &moa_core::types::context::ContextMessage) -> bool {
    [
        "<system-reminder>",
        "<available_skills>",
        "<memory-reminder",
        "<memory_digest",
        "<session_checkpoint",
    ]
    .iter()
    .any(|prefix| message.content.starts_with(prefix))
}

fn is_compaction_request<R: CompletionRequestView + ?Sized>(request: &R) -> bool {
    request.tools().is_empty()
        && request.max_output_tokens() == Some(COMPACTION_MAX_OUTPUT_TOKENS)
        && request.messages().iter().any(|message| {
            message
                .content
                .contains("New events to fold into the checkpoint")
        })
}

fn recorded_compaction_events() -> Vec<ProviderEvent> {
    vec![
        ProviderEvent::TextDelta {
            text: RECORDED_COMPACTION_SUMMARY.to_string(),
        },
        ProviderEvent::Usage {
            usage: TokenUsage::default(),
        },
        ProviderEvent::Terminal {
            stop_reason: StopReason::EndTurn,
        },
    ]
}

fn response_from_events(events: Vec<ProviderEvent>, model: ModelId) -> CompletionResponse {
    let mut text = String::new();
    let mut content = Vec::new();
    let mut usage = TokenUsage::default();
    let mut stop_reason = StopReason::EndTurn;

    for event in events {
        match event {
            ProviderEvent::TextDelta { text: delta } => {
                text.push_str(&delta);
                content.push(CompletionContent::Text(delta));
            }
            ProviderEvent::ToolCall { call } => {
                content.push(CompletionContent::ToolCall(call));
            }
            ProviderEvent::Usage { usage: event_usage } => {
                usage = event_usage;
            }
            ProviderEvent::Terminal {
                stop_reason: event_stop_reason,
            } => {
                stop_reason = event_stop_reason;
            }
        }
    }

    CompletionResponse {
        text,
        content,
        stop_reason,
        model,
        usage,
        duration_ms: 0,
        thought_signature: None,
    }
}
